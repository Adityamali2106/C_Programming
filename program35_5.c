void Reverse(char *str)
{
	char ch = '\0';
	int iCnt1 = 0;
	int iCnt2 = 0;

	if(*str == '\0')
	{
		return;
	}

	while(str[iCnt1] != '\0')
	{
		 iCnt1++;
	}
	iCnt1--;

	for (iCnt2 = 0; iCnt2 < iCnt1; iCnt2++)
	{
		ch = str[iCnt1];
		str[iCnt1]  = str[iCnt2];
		str[iCnt2] = ch;

		iCnt1--;
	}

	printf("%s\n", str);
}	// End of Reverse

