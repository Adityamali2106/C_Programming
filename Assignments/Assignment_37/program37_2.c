int CheckChar(char *str, char ch)
{
	int iCount = 0;

	if(*str == '\0')
	{
		return 0;
	}

	while(*str != '\0')
	{
		if ((*str) == ch)
		{
			iCount++;
		}
		*str++;
	}

	return iCount;
}	// End of CountWhite

