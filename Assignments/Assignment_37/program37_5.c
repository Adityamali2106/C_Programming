void StrRevX(char *str)
{
	char cTemp = '\0';
	char *start = str;
	char *end = str;

	while(*end != '\0')
	{
		end++;
	}

	end--;

	while(start < end)
	{
		cTemp = *start;
		*start = *end;
		*end = cTemp;
		start++;
		end--;
	}
}	// End of StrrevX

