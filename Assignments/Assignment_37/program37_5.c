int main()
{
	char Arr[50] = {'\0'};

	printf("Enter the String : \t");
	scanf("%[^'\n']s",Arr);

	StrRevX(Arr);

	printf("Reversed string is : %s\n", Arr);

    return 0;
}   // End of main

