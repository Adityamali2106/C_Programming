#include <stdio.h>

typedef unsigned int UNIT;

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: OffBit
//  Discription 	: It is used to off 7th & 10th bit of given number if it is on. Return modified number.
//  Input 			: Unsigned Integer
//  Output 			: Boolen
//  Author 			: Aditya Vijay Mali
//  Date 			: 06/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

UNIT OffBit(UNIT iNo)
{
	UNIT iMask = 0xfffffdbf;
	UNIT iResult = 0;

	iResult = iNo & iMask;

	return iResult;
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main(void)
{
	UNIT iNo = 0;
	UNIT iRet = 0;

	printf("Enter Number : \n");
	scanf("%d",&iNo);

	iRet = OffBit(iNo);

	printf("Modified number is : %d\n", iRet);

	return 0;
}