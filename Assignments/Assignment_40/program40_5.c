void Display(int iNo)
{
	static char cCnt = 'a';

	if(cCnt != ('a'+ iNo))
	{
		printf("%c\t",cCnt);
		cCnt++;
		Display(iNo);
	}
}	// End of Display

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
