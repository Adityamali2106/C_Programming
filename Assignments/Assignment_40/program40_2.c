void Display(int iNo)
{
	static int iCnt = 1;
	if(iCnt <= iNo)
	{
		printf("%d\t", iCnt);
		iCnt++;
		Display(iNo);
	}	
}	// End of Display

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	int iValue = 0;

	printf("Enter Number :\n");
	scanf("%d",&iValue);

	Display(iValue);
    return 0;
}   // End of main

