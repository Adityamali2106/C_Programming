int SumDigit(int iNo)
{
	static int iSum = 0;
	int iDigit = 0;
	if(iNo != 0)
	{
		iDigit = iNo % 10;
		iNo = iNo / 10;
		iSum = (iSum + iDigit);
		SumDigit(iNo);
	}
	return iSum;
}	// End of SumDigit

