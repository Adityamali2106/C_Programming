///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	int iValue = 0,iRet = 0;

	printf("Enter Number :\n");
	scanf("%d",&iValue);

	iRet = SumDigit(iValue);
   
    printf("Summation of Digit is : %d\n", iRet);
    return 0;
}   // End of main

