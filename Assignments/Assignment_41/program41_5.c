///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : Mult
//  Discription :   It is used to calculate product of its digits.
//  Input :         Integer
//  Output :        Integer
//  Author :        Aditya Mali
//  Date :          04/12/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

int Mult(int iNo)
{
	static int iMult = 1;
	int iDigit = 0;
	if(iNo != 0)
	{
		iDigit = iNo % 10;
		iNo = iNo / 10;
		iMult = (iMult * iDigit);
		Mult(iNo);
	}
	return iMult;
}	// End of Mult

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	int iValue = 0,iRet = 0;

	printf("Enter Number :\n");
	scanf("%d",&iValue);

	iRet = Mult(iValue);
   
    printf("Product of Digit is : %d\n", iRet);
    return 0;
}   // End of main

