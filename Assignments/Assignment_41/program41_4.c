#include<stdio.h>               // For Input Output 

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : Fact
//  Discription :   It is used to Calculate factorial of given number.
//  Input :         Integer.
//  Output :        Integer
//  Author :        Aditya Mali
//  Date :          04/12/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

int Fact(int iNo)
{
	static int iFact = 1;
	if(iNo != 0)
	{
		iFact = iFact * iNo;
		iNo--;
		Fact(iNo);
	}
	return iFact;
}	// End of Fact

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	int iValue = 0;
	int iRet = 0;

	printf("Enter String :\n");
	scanf("%d",&iValue);

	iRet = Fact(iValue);
   
    printf("Factorial is : %d\n", iRet);
    return 0;
}   // End of main

