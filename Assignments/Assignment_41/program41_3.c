int Strlen(char *str)
{
	static int iCount = 0;
	if(*str != '\0')
	{
		iCount++;
		str++;
		Strlen(str);
	}
	return iCount;
}	// End of Strlen

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char Arr[20] = {'\0'};
	int iRet = 0;

	printf("Enter String :\n");
	scanf("%[^'\n']s",Arr);

	iRet = Strlen(Arr);
   
    printf("Count of characters is : %d\n", iRet);
    return 0;
}   // End of main

