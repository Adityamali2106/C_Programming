///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Discription :   It is used to display a pattern by recursive approch.
//  Input :         Integer
//  Output :        void
//  Author :        Aditya Mali
//  Date :          03/12/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
	if(iNo >= 1)
	{
		printf("%d\t*\t", iNo);
		iNo--;
		Display(iNo);
	}	
}	// End of Display

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	int iValue = 0;

	printf("Enter Number :\n");
	scanf("%d",&iValue);

	Display(iValue);
    return 0;
}   // End of main

