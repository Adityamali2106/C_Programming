///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : Pattern
//  Discription :   It is used to display the pattern 
//  Input :         Integer
//  Output :        Void
//  Author :        Aditya Mali
//  Date :          21/11/2025
//
