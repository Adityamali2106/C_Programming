void Pattern(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("%d\t", 2 * iCnt);
    }

    printf("\n");
}   // End of Pattern

//  O(N)

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter Number of elements \n");
    scanf("%d", &iValue);

    Pattern(iValue);

    return 0;
}   // End of main

