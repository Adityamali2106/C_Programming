void strlwrX(char *str)
{
	if(*str == '\0')
	{
		return;
	}

	while(*str != '\0')
	{
		if ((*str) >= 'A' && (*str) <= 'Z')
		{
			*str = (*str) + 32;
		}

		*str++;
	}	
}	// End of strlwrX

