///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : CountWhite
//  Discription :   It is used to Count White spaces from given string.
//  Input :         Character pointer
//  Output :        Integer
//  Author :        Aditya Mali
//  Date :          28/11/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

int CountWhite(char *str)
{
	int iCount = 0;

	if(*str == '\0')
	{
		return iCount;
	}

	while(*str != '\0')
	{
		if ((*str) == ' ')
		{
			iCount++;
		}
		*str++;
	}

	return iCount;
}	// End of CountWhite

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char Arr[50] = {'\0'};
	int iRet = 0;

	printf("Enter the character : \t");
	scanf("%[^'\n']s",Arr);

	iRet = CountWhite(Arr);

	printf("Count of White spaces is : %d\n", iRet);

    return 0;
}   // End of main

