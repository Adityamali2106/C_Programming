void DisplayDigit(char *str)
{
	if(*str == '\0')
	{
		return;
	}

	while(*str != '\0')
	{
		if ((*str) >= '0' && (*str) <= '9')
		{
			printf("%c",(*str));
		}
		*str++;
	}
	printf("\n");
}	// End of DisplayDigit

