void strtoggleX(char *str)
{
	if(*str == '\0')
	{
		return;
	}

	while(*str != '\0')
	{
		if ((*str) >= 'a' && (*str) <= 'z')
		{
			*str = (*str) - 32;
		}
		else if ((*str) >= 'A' && (*str) <= 'Z')
		{
			*str = (*str) + 32;
		}

		*str++;
	}	
}	// End of strtoggleX

