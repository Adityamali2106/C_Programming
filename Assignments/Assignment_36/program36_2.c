void struprX(char *str)
{
	if(*str == '\0')
	{
		return;
	}

	while(*str != '\0')
	{
		if ((*str) >= 'a' && (*str) <= 'z')
		{
			*str = (*str) - 32;
		}

		*str++;
	}	
}	// End of struprX

