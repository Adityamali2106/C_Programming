#include<stdio.h>               // For Input Output 

#define TRUE 1 					// Defining Micro for Boolen datatype
#define FALSE 0	

typedef int BOOL;
///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : ChkCapital
//  Discription :   It is used check whether it is Capital alphabet or not (A-Z) 
//  Input :         Character
//  Output :        Boolen
//  Author :        Aditya Mali
//  Date :          28/11/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkCapital(char ch)
{
	if ((ch >= 'A') && (ch <= 'Z'))
	{
		return TRUE;
	}
	else
	{
		return FALSE;
	}
}	//End of ChkCapital

//  O(N)

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char cValue = '\0';
	BOOL bRet = FALSE;

	printf("Enter the character : \t");
	scanf("%c",&cValue);

	bRet = ChkCapital(cValue);

	if (bRet == TRUE)
	{
		printf("It is Capital Character\n");
	}
	else
	{
		printf("It is Not Capital Character\n");
	}

    return 0;
}   // End of main

