#include<stdio.h>               // For Input Output 

#define TRUE 1 					// Defining Micro for Boolen datatype
#define FALSE 0	

typedef int BOOL;
///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : ChkSmall
//  Discription :   It is used check whether it is small case alphabet or not (a-z) 
//  Input :         Character
//  Output :        Boolen
//  Author :        Aditya Mali
//  Date :          28/11/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkSmall(char ch)
{
	if ((ch >= 'a') && (ch <= 'z'))
	{
		return TRUE;
	}
	else
	{
		return FALSE;
	}
}	//End of ChkSmall

//  O(N)

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char cValue = '\0';
	BOOL bRet = FALSE;

	printf("Enter the character : \t");
	scanf("%c",&cValue);

	bRet = ChkSmall(cValue);

	if (bRet == TRUE)
	{
		printf("It is Small case Character \n");
	}
	else
	{
		printf("It is Not a Small case Character \n");
	}

    return 0;
}   // End of main

