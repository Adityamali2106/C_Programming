#include<stdio.h>               // For Input Output 

#define TRUE 1 					// Defining Micro for Boolen datatype
#define FALSE 0	

typedef int BOOL;
///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : ChkDigit
//  Discription :   It is used check whether it is Digit or not (0-9) 
//  Input :         Character
//  Output :        Boolen
//  Author :        Aditya Mali
//  Date :          28/11/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkDigit(char ch)
{
	if ((ch >= '0') && (ch <= '9'))
	{
		return TRUE;
	}
	else
	{
		return FALSE;
	}
}	//End of ChkDigit

//  O(N)

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char cValue = '\0';
	BOOL bRet = FALSE;

	printf("Enter the character : \t");
	scanf("%c",&cValue);

	bRet = ChkDigit(cValue);

	if (bRet == TRUE)
	{
		printf("It is Digit \n");
	}
	else
	{
		printf("It is Not Digit \n");
	}

    return 0;
}   // End of main

