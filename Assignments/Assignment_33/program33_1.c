#include<stdio.h>               // For Input Output 

#define TRUE 1 					// Defining Micro for Boolen datatype
#define FALSE 0	

typedef int BOOL;
///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : ChkAlpha
//  Discription :   It is used check whether it is alphabet or not (A-Z a-z) 
//  Input :         Character
//  Output :        Boolen
//  Author :        Aditya Mali
//  Date :          28/11/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkAlpha(char ch)
{
	if ((ch >= 'A') && (ch <= 'Z') || (ch >= 'a') && (ch <= 'z'))
	{
		return TRUE;
	}
	else
	{
		return FALSE;
	}
}	//End of ChkAlpha

//  O(N)

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char cValue = '\0';
	BOOL bRet = FALSE;

	printf("Enter the character : \t");
	scanf("%c",&cValue);

	bRet = ChkAlpha(cValue);

	if (bRet == TRUE)
	{
		printf("It is Character\n");
	}
	else
	{
		printf("It is Not Character\n");
	}

    return 0;
}   // End of main

