#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Min
//  Discription 	: It is used to find smallest digit from given number digits Recursively
//  Input 			: Integer
//  Output 			: Smallest of its digits
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

int Min(int iNo)
{
    static int iMin = 9; 
    int iDigit = 0;
    
    if(iNo != 0)
    {
        iDigit = iNo % 10; 
        if (iDigit < iMin)
        {
            iMin = iDigit;
        }        
        Min(iNo/10);
    }

    return iMin;
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter Number :\n");
    scanf("%d",&iValue);

    iRet = Min(iValue);

    printf("Smallest digit is : %d\n",iRet);

    return 0;
}