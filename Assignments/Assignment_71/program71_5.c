#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Reverse
//  Discription 	: It is used to reverse digit of given number, Recursively.
//  Input 			: Integer
//  Output 			: Reverse of its digits
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

int Reverse(int iNo,int iRev)
{    
    if(iNo == 0)
    {
        return iRev;
    }

    return Reverse(iNo /10,iRev *10 + iNo % 10);
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter Number :\n");
    scanf("%d",&iValue);

    iRet = Reverse(iValue,0);

    printf("Reversed Number is : %d\n",iRet);

    return 0;
}