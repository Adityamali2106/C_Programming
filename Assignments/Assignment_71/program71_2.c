#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Max
//  Discription 	: It is used to find Largest digit from given number digits Recursively
//  Input 			: Integer
//  Output 			: Largest of its digits
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

int Max(int iNo)
{
    static int iMax = 0; 
    int iDigit = 0;
    
    if(iNo != 0)
    {
        iDigit = iNo % 10; 
        if (iDigit > iMax)
        {
            iMax = iDigit;
        }        
        Max(iNo/10);
    }

    return iMax;
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter Number :\n");
    scanf("%d",&iValue);

    iRet = Max(iValue);

    printf("Largest digit is : %d\n",iRet);

    return 0;
}