#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name   : Display
//  Discription     : It is used to display * 5 times on screen Recursively
//  Input           : Nothing
//  Output          : Nothing
//  Author          : Aditya Vijay Mali
//  Date            : 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

void Display()
{
    static int iNo = 1;

    if(iNo <= 5)
    {
        printf("*\t");
        iNo++;
        Display();
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}