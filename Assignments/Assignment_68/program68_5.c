#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name   : Display
//  Discription     : It is used to display a to f On screen Recursively
//  Input           : Nothing
//  Output          : Nothing
//  Author          : Aditya Vijay Mali
//  Date            : 07/02/2026
