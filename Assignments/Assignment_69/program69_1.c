#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Display
//  Discription 	: It is used to display * n times Recursively
//  Input 			: Integer
//  Output 			: Nothing
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{

    if(iNo != 0)
    {
        printf("*\t");
        Display(--iNo);
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iNo = 0;

    printf("Enter Number :\n");
    scanf("%d",&iNo);

    Display(iNo);

    return 0;
}