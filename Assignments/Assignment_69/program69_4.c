#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Display
//  Discription 	: It is used to display A to Z spacific to the N on screen Recursively
//  Input 			: Integer
//  Output 			: Nothing
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    static char ch = 'A';

    if(iNo >= 1)
    {
        printf("%c\t",ch);
        ch++;
        Display(--iNo);
    }}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iNo = 0;

    printf("Enter Number :\n");
    scanf("%d",&iNo);

    Display(iNo);

    return 0;
}