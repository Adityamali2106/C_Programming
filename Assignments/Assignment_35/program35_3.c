int Difference(char *str)
{
	int iCount1 = 0;
	int iCount2 = 0;

	if(*str == '\0')
	{
		return 0;
	}

	while(*str != '\0')
	{
		if ((*str) >= 'a' && (*str) <= 'z')
		{
			iCount1++;
		}
		else if ((*str) >= 'A' && (*str) <= 'Z')
		{
			iCount2++;
		}

		*str++;
	}	

	return (iCount1 - iCount2);
}	// End of Difference

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char Arr[50] = {'\0'};
	int iRet = 0;

	printf("Enter the character : \t");
	scanf("%[^'\n']s",Arr);

	iRet = Difference(Arr);

	printf("Difference between Small character and capital character is :%d\n", iRet);

    return 0;
}   // End of main

