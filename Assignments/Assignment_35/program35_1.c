///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : CountCapital
//  Discription :   It is used to count Number of Capital characters from string.
//  Input :         Character
//  Output :        void
//  Author :        Aditya Mali
//  Date :          28/11/2025
//
