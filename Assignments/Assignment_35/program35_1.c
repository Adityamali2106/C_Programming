int CountCapital(char *str)
{
	int iCnt = 0;

	if(*str == '\0')
	{
		return 0;
	}

	while(*str != '\0')
	{
		if ((*str) >= 'A' && (*str) <= 'Z')
		{
			iCnt++;
		}

		*str++;
	}	

	return iCnt;
}	// End of CountCapital

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
