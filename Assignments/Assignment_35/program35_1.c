///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char Arr[50] = {'\0'};
	int iRet = 0;

	printf("Enter the character : \t");
	scanf("%[^'\n']s",Arr);

	iRet = CountCapital(Arr);

	printf("Number of Capital character is :%d\n", iRet);

    return 0;
}   // End of main

