#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Mult
//  Discription 	: It is used to calculate Product of given number digits Recursively
//  Input 			: Integer
//  Output 			: Product of digit
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

int Mult(int iNo)
{
    static int iSum = 1; 
    
    if(iNo != 0)
    {
        iSum = iSum * (iNo % 10);
        Mult(iNo/10);
    }

    return iSum;
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter Number :\n");
    scanf("%d",&iValue);

    iRet = Mult(iValue);

    printf("Product of the %d is %d\n",iValue,iRet);

    return 0;
}