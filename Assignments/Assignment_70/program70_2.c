///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Sum
//  Discription 	: It is used to calculate Summation of given number digits Recursively
//  Input 			: Integer
//  Output 			: Summation of its digits
//  Author 			: Aditya Vijay Mali
