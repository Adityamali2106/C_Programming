int Sum(int iNo)
{
    static int iSum = 0; 
    
    if(iNo != 0)
    {
        iSum = iSum + (iNo % 10); 
        Sum(iNo/10);
    }

    return iSum;
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter Number :\n");
    scanf("%d",&iValue);

    iRet = Sum(iValue);

    printf("%d\n",iRet);

    return 0;
}