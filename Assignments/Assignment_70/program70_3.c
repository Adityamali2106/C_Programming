///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Strlen
//  Discription 	: It is used to calculate the length of the string Recursively
//  Input 			: String 
//  Output 			: Length of the string
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

int MyStrlen(char *str)
{
    static int iLength = 0; 
    
    if(str[iLength] != '\0')
    {
        iLength++;
        MyStrlen(str);
    }

    return iLength;
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20] = {'\0'};
    int iRet = 0;

    printf("Enter String :\n");
    scanf("%[^'\n']s",arr);

    iRet = MyStrlen(arr);

    printf("Length of the string is : %d\n",iRet);

    return 0;
}