#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name 	: Fact
//  Discription 	: It is used to calculate factorial of give number
//  Input 			: Integer
//  Output 			: Factorial of given number
//  Author 			: Aditya Vijay Mali
//  Date 			: 07/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////

int Fact(int iNo)
{
    static int iFact = 1;
    if(iNo != 1)
    {
        iFact = iFact * iNo;
        Fact(--iNo);
    }
    return iFact;    
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iNo = 0;
    int iRet = 0;

    printf("Enter Number :\n");
    scanf("%d",&iNo);

    iRet = Fact(iNo);

    printf("Factorial of %d is %d",iNo,iRet);

    return 0;
}