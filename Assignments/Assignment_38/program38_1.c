///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : StrCpyRevX
//  Discription :   It is used to copy characters of string into another string in reverse order.
//  Input :         Character pointer
//  Output :        void
//  Author :        Aditya Mali
//  Date :          01/12/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////
void StrCpyRevX(char *src, char *dest)
{
	char *cTemp = src;

	while(*src != '\0')
	{
		src++;
	}

	src--;

	while(src >= cTemp)
	{
		*dest = *src;
		dest++;
		src--;
	}
}	// End of StrrevX

