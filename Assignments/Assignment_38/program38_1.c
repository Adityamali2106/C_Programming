///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char Arr[30] = {'\0'};
	char Brr[30] = {'\0'};

	printf("Enter the String : \t");
	scanf("%[^'\n']s",Arr);

	StrCpyRevX(Arr,Brr);

	printf("Copied string is : %s\n",Brr);

    return 0;
}   // End of main

