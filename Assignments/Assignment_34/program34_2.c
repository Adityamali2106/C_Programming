///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Discription :   It is used to display samll case to capital Character and if it is capital
//					then display its corresponding capital,in other cases display as it is. 
//  Input :         Character
//  Output :        Void
//  Author :        Aditya Mali
//  Date :          28/11/2025
//
///////////////////////////////////////////////////////////////////////////////////////////////

void Display(char ch)
{
	if ((ch >= 'a') && (ch <= 'z'))
	{
		printf("%c\n", ch - 32);
	}
	else if (ch >= 'A' && ch <= 'Z')
	{
		printf("%c\n", ch + 32);
	}
	else
	{
		printf("%c\n", ch);
	}
}	//End of Display

//  O(N)

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char cValue = '\0';

	printf("Enter the character : \t");
	scanf("%c",&cValue);

	Display(cValue);

    return 0;
}   // End of main

