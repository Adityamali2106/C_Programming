#include<stdio.h>               // For Input Output 

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Discription :   It is used to display ASCII value in decimal octal and hexadecimal format
//  Input :         Character
//  Output :        void
//  Author :        Aditya Mali
//  Date :          28/11/2025
