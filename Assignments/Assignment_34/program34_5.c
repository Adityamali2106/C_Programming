///////////////////////////////////////////////////////////////////////////////////////////////

void Display(char ch)
{
	printf("%d\n", ch);
	printf("%#o\n", ch);
	printf("%#x\n", ch);
}	//End of DisplayASCII

//  O(N)

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entory Point Function for the application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	char cValue = '\0';

	printf("Enter the character : \t");
	scanf("%c",&cValue);

	Display(cValue);

    return 0;
}   // End of main
